#!/usr/bin/env node
/**
 * Seals (encrypts) your private invite details so they can live in a public repo.
 *
 *   node tools/seal.mjs
 *
 * Reads   private/secrets.json      (git-ignored: address, phone, RSVP link…)
 * Writes  sealed.js                 (safe to commit: AES-GCM ciphertext only)
 *         private/Code.gs           (the Google Apps Script to paste, with your RSVP token)
 *         private/invite-link.txt   (the link to send your friends — it contains the key)
 *
 * The key is created once and kept in private/secrets.json, so re-sealing after an
 * edit keeps the same invite link working. Nothing here talks to the network.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { webcrypto as crypto } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const secretsPath = path.join(root, 'private', 'secrets.json');
const AAD = new TextEncoder().encode('diwali-party/v1');
const b64url = (bytes) => Buffer.from(bytes).toString('base64url');
const b64 = (bytes) => Buffer.from(bytes).toString('base64');
const secretFile = { encoding: 'utf8', mode: 0o600 };

const secrets = JSON.parse(await readFile(secretsPath, 'utf8'));
if (!secrets.invite) throw new Error('private/secrets.json needs an "invite" object');
if (!secrets.siteUrl) throw new Error('private/secrets.json needs a "siteUrl"');

// One-time: create a random 128-bit key and a random RSVP token.
let created = false;
if (!secrets.key) { secrets.key = b64url(crypto.getRandomValues(new Uint8Array(16))); created = true; }
if (!secrets.rsvpToken) { secrets.rsvpToken = b64url(crypto.getRandomValues(new Uint8Array(18))); created = true; }
if (created) await writeFile(secretsPath, JSON.stringify(secrets, null, 2) + '\n', secretFile);

const rawKey = Buffer.from(secrets.key, 'base64url');
if (rawKey.length !== 16 && rawKey.length !== 32) throw new Error('key must be 16 or 32 bytes');

const key = await crypto.subtle.importKey('raw', rawKey, 'AES-GCM', false, ['encrypt']);
const iv = crypto.getRandomValues(new Uint8Array(12));
const payload = { ...secrets.invite, rsvpToken: secrets.rsvpToken };
const ciphertext = await crypto.subtle.encrypt(
  { name: 'AES-GCM', iv, additionalData: AAD },
  key,
  new TextEncoder().encode(JSON.stringify(payload)),
);

const sealed = { v: 1, iv: b64(iv), ct: b64(new Uint8Array(ciphertext)) };
await writeFile(
  path.join(root, 'sealed.js'),
  '/* Encrypted invite details (AES-GCM). Unreadable without the key, which lives only in the invite link.\n' +
  '   Generated by tools/seal.mjs. Do not edit by hand. */\n' +
  `window.SEALED = ${JSON.stringify(sealed)};\n`,
);

const gsTemplate = await readFile(path.join(root, 'apps-script', 'Code.gs'), 'utf8');
await writeFile(path.join(root, 'private', 'Code.gs'), gsTemplate.replace('__RSVP_TOKEN__', secrets.rsvpToken), secretFile);

const link = `${secrets.siteUrl.replace(/\/?$/, '/')}#k=${secrets.key}`;
await writeFile(path.join(root, 'private', 'invite-link.txt'), link + '\n', secretFile);

console.log('🪔 Sealed sealed.js');
console.log(`   RSVP endpoint: ${secrets.invite.rsvpUrl ? 'set' : 'NOT SET (guests will be offered WhatsApp instead)'}`);
console.log('   Apps Script to paste: private/Code.gs');
console.log(`   Invite link: ${link}`);
